"""Registry ports: read models, write capabilities, and the aggregate."""

from __future__ import annotations

from typing import Any, Protocol

from pyverge.core.types import (
    Attachable,
    ModelHandle,
    ModelKind,
    ModelVersionKey,
)
from pyverge.versioning import (
    EdgeKey,
    Migratable,
    Transitional,
    Versionable,
    VersionEdge,
    VersionNode,
)


class ModelCatalog(Protocol):
    """Read-only model surface used by discovery and planning."""

    @property
    def name(self) -> str: ...
    @property
    def versions(self) -> list[VersionNode]: ...
    @property
    def kinds(self) -> list[ModelKind]: ...
    @property
    def entities(self) -> list[ModelKind]: ...
    def models(self, kind: ModelKind | None) -> frozenset[ModelHandle]: ...
    def kind_versions(self, kind: ModelKind) -> list[VersionNode]: ...
    def has_model(self, key: Any) -> bool: ...
    def find_model(self, key: Any) -> VersionNode | None: ...
    def get_model(self, key: Any) -> VersionNode: ...
    def get_model_by_handle(self, handle: ModelHandle) -> VersionNode: ...
    def latest(self, kind: ModelKind) -> VersionNode: ...
    def earliest(self, kind: ModelKind) -> VersionNode: ...
    @property
    def latest_version(self) -> VersionNode: ...
    def missing_references(self, node: Versionable) -> frozenset[ModelVersionKey]: ...


class PathCatalog(Protocol):
    """Narrow read port needed to resolve migration paths."""

    def migration_path(
        self, from_version: Versionable, to_version: Versionable
    ) -> list[tuple[VersionNode, VersionNode]]: ...


class ContentHashLookup(Protocol):
    """Optional content-address index for manifest/debug queries."""

    def find_edge_by_content_hash(self, value: str) -> EdgeKey | None: ...


class GraphCatalog(PathCatalog, ModelCatalog, Protocol):
    """Read-only migration graph surface used by runtime planning."""

    def migrations(self, kind: ModelKind) -> list[Migratable]: ...
    def migrations_of(self, key: Any) -> frozenset[Migratable]: ...
    def has_migration(self, key: Transitional) -> bool: ...
    def get_migration(self, key: Transitional) -> Migratable: ...
    def get_migration_by_edge(self, key: Transitional) -> Migratable: ...
    def is_adjacent(self, key: Transitional) -> bool: ...
    def is_critical_edge(self, key: Transitional) -> bool: ...
    def has_hooks(self, key: Transitional) -> bool: ...
    def hooks(self, key: Transitional | None = None) -> list[Attachable]: ...
    def get_hooks(self, key: Transitional) -> list[Attachable]: ...
    def snapshot(self) -> GraphCatalog: ...


class ModelWrite(Protocol):
    """Write-side model capability."""

    def store_model(self, version: VersionNode) -> VersionNode: ...
    def reconcile_model(self, version: VersionNode) -> VersionNode: ...
    def remove_model(self, key: Any) -> None: ...
    def remove_model_by_handle(self, handle: ModelHandle) -> None: ...
    def clear_models(self) -> None: ...


class MigrationWrite(Protocol):
    """Write-side migration capability."""

    def store_migration(self, key: VersionEdge) -> Any: ...
    def remove_migration(self, key: Transitional) -> None: ...
    def remove_migration_range(
        self, from_version: Versionable, to_version: Versionable
    ) -> None: ...
    def clear_migrations(self) -> None: ...
    def add_hook(self, key: Transitional, hook: Attachable) -> None: ...
    def remove_hook(
        self, key: Transitional, hook: Attachable | None = None
    ) -> None: ...
    def clear_hooks(self, key: Transitional | None = None) -> None: ...


class RegistryPort(GraphCatalog, ModelWrite, MigrationWrite, Protocol):
    """Full catalog contract for an in-memory or remote adapter."""


__all__ = [
    "ContentHashLookup",
    "GraphCatalog",
    "MigrationWrite",
    "ModelCatalog",
    "ModelWrite",
    "PathCatalog",
    "RegistryPort",
]
